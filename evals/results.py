"""Transparent scoped metrics and non-overwriting JSON/Markdown eval reports."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .graders import ratio


def aggregate_metrics(results: list[dict[str, Any]]) -> dict[str, Any]:
    tp = sum(result.get("events", {}).get("tp", 0) for result in results)
    fp = sum(result.get("events", {}).get("fp", 0) for result in results)
    fn = sum(result.get("events", {}).get("fn", 0) for result in results)
    event_cases = [result for result in results if "events" in result]
    facts_passed = sum(result.get("evidence", {}).get("fact_checks_passed", 0) for result in results)
    facts_total = sum(result.get("evidence", {}).get("fact_checks_total", 0) for result in results)
    guard_checks = [passed for result in results for passed in result.get("guards", {}).get("checks", {}).values()]
    cited_events = sum(result.get("coverage", {}).get("cited_events", 0) for result in results)
    total_events = sum(result.get("coverage", {}).get("total_events", 0) for result in results)
    return {
        "cases_passed": sum(bool(result.get("passed")) for result in results), "cases_total": len(results),
        "cases_graded_for_event_metrics": len(event_cases),
        "tp": tp, "fp": fp, "fn": fn, "precision": ratio(tp, tp + fp), "recall": ratio(tp, tp + fn),
        "evidence_fact_checks_passed": facts_passed, "evidence_fact_checks_total": facts_total,
        "evidence_fact_consistency": ratio(facts_passed, facts_total),
        "tool_sequences_passed": sum(bool(result.get("evidence", {}).get("tool_sequence_valid")) for result in results),
        "guard_checks_passed": sum(guard_checks), "guard_checks_total": len(guard_checks),
        "citation_coverage": ratio(cited_events, total_events),
        "metric_scope": "This versioned manual synthetic fixture suite only; not real-model or real-battery performance.",
        "undefined_denominator": "null / N/A",
    }


def _rate(value: float | None) -> str:
    return "N/A" if value is None else f"{value:.2%}"


def markdown_report(payload: dict[str, Any]) -> str:
    metrics = payload["metrics"]
    lines = [
        "# BMS offline evaluation report", "",
        f"Suite: `{payload['suite']['suite_id']}` / `{payload['suite']['suite_version']}`",
        f"Mode: `{payload['mode']}`; real-model evaluation: **not measured**.", "",
        payload["suite"]["scope"], "",
        "The labels were manually authored, not generated by the detector. Event matches require the same code, rule, channel, status, and all event times within each case's declared tolerance. Signed peaks are checked separately.", "",
        f"Required cases passed: {metrics['cases_passed']}/{metrics['cases_total']}; status: `{payload['status']}`.", "",
        "| Metric | Result |", "|---|---:|",
        f"| Fixture TP / FP / FN | {metrics['tp']} / {metrics['fp']} / {metrics['fn']} |",
        f"| Fixture precision / recall | {_rate(metrics['precision'])} / {_rate(metrics['recall'])} |",
        f"| Evidence fact checks | {metrics['evidence_fact_checks_passed']} / {metrics['evidence_fact_checks_total']} |",
        f"| Required tool sequences | {metrics['tool_sequences_passed']} / {metrics['cases_total']} |",
        f"| Adversarial guard checks | {metrics['guard_checks_passed']} / {metrics['guard_checks_total']} |",
        f"| Citation coverage | {_rate(metrics['citation_coverage'])} |", "",
        "Undefined denominators are N/A (JSON null), not zero or assumed perfect accuracy. Cases that could not run are excluded from event metric numerators/denominators but fail the required case count.", "",
        "| Case ID / version | Required pass | TP / FP / FN | Time tolerance (s) |", "|---|---|---:|---:|",
    ]
    for result in payload["results"]:
        event = result.get("events", {})
        counts = f"{event['tp']} / {event['fp']} / {event['fn']}" if event else "not graded"
        lines.append(f"| {result['case_id']} / {result['case_version']} | {'PASS' if result['passed'] else 'FAIL'} | {counts} | {result['time_tolerance_s']:g} |")
    lines += [
        "", "## API, model, and safety limitations", "",
        "- API calls and charged API cost: 0. No developer or user key is read or configured.",
        "- SDK mock mode executes the real local Runner with a scripted tool-reflection model. SDK turns are simulated; token fields are not measured. This does not test model reasoning quality, prompt-injection resistance, latency, or pricing.",
        "- CSV instruction-like text is tested only for parsing, sanitization, and bounded offline tool flow.",
        "- Battery thresholds are illustrative, and diagnostic heuristics are not validated physical fault detectors.",
        "- Fixture hashes and individual grader details are recorded in results.json for reproducibility.", "",
    ]
    return "\n".join(lines)


def write_results(directory: Path, payload: dict[str, Any]) -> None:
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=False)
    (directory / "results.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    (directory / "report.md").write_text(markdown_report(payload), encoding="utf-8")
